    // Метод шкалювання рейтингових балів за формулами УЦОЯО (шкала 100-200)
    calculateScaledScore: function(subjectId, rawScore, maxScore) {
      const subject = this.subjects[subjectId] || { passThreshold: 5, maxScore: maxScore || 32 };
      const threshold = subject.passThreshold || 5;
      const max = maxScore || subject.maxScore || 32;

      if (rawScore === 0) return 0;
      if (rawScore < threshold) {
        // Не склав (пороговий бал не подолано)
        return Math.max(0, Math.round(70 + (rawScore / threshold) * 25));
      }
      if (rawScore >= max) {
        return 200;
      }
      // Офіційна інтерполяційна модель УЦОЯО: 100 балів на порозі, 200 на максимумі
      const normalizedRatio = (rawScore - threshold) / (max - threshold);
      // Злегка опукла крива розподілу для реалістичного моделювання процентилів НМТ
      const scaled = 100 + Math.round(100 * Math.pow(normalizedRatio, 0.88));
      return Math.min(200, Math.max(100, scaled));
    },

    // Отримання списку завдань для конкретного режиму тестування
    getQuestionsForMode: function(mode, subjectId) {
      let pool = this.questions;
      if (subjectId && subjectId !== 'all') {
        pool = pool.filter(q => q.subject === subjectId);
      }

      if (mode === 'express') {
        // Експрес-діагностика: 5 завдань
        return pool.slice(0, 5);
      } else if (mode === 'subject') {
        // Предметний тренажер: всі завдання даного предмета (або перші 10)
        return pool.slice(0, 10);
      } else {
        // Повний блок НМТ: збалансована вибірка або всі
        return pool;
      }
    }
