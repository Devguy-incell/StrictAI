  function pickNextQuestion(targetLevel) {
    var pool = QUESTION_BANK[state.selectedSubject] || QUESTION_BANK['Математика'];
    var unused = pool.filter(function (q) {
      return state.askedIds.indexOf(q.id) === -1;
    });
    if (!unused.length) return null;

    var lastFormat = state.answers.length
      ? state.answers[state.answers.length - 1].format
      : null;

    unused.sort(function (a, b) {
      var distA = Math.abs(a.level - targetLevel);
      var distB = Math.abs(b.level - targetLevel);
      if (distA !== distB) return distA - distB;
      var fmtPenaltyA = a.format === lastFormat ? 1 : 0;
      var fmtPenaltyB = b.format === lastFormat ? 1 : 0;
      return fmtPenaltyA - fmtPenaltyB;
    });

    return unused[0];
  }

