  function findDiscipline(queryVal) {
    if (!queryVal) return null;
    var q = String(queryVal).trim().toLowerCase();
    for (var i = 0; i < DISCIPLINES.length; i++) {
      var d = DISCIPLINES[i];
      if (d.id.toLowerCase() === q || d.slug.toLowerCase() === q) return d;
      if (d.aliases && d.aliases.indexOf(q) !== -1) return d;
    }
    for (var j = 0; j < DISCIPLINES.length; j++) {
      var dj = DISCIPLINES[j];
      if (dj.id.toLowerCase().indexOf(q) !== -1 || q.indexOf(dj.slug) !== -1) {
        return dj;
      }
    }
    return null;
  }

  function findUniversity(queryVal) {
    if (!queryVal) return null;
    var q = String(queryVal).trim().toLowerCase();
    for (var i = 0; i < UNIVERSITIES.length; i++) {
      var u = UNIVERSITIES[i];
      if (u.id.toLowerCase() === q || u.label.toLowerCase() === q || u.shortLabel.toLowerCase() === q) {
        return u;
      }
      if (u.aliases && u.aliases.indexOf(q) !== -1) return u;
    }
    for (var j = 0; j < UNIVERSITIES.length; j++) {
      var uj = UNIVERSITIES[j];
      if (uj.label.toLowerCase().indexOf(q) !== -1 || q.indexOf(uj.id.split('-')[0]) !== -1) {
        return uj;
      }
    }
    return null;
  }

