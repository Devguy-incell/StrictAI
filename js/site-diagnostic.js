  function updatePaceUI(elapsedSec) {
    var remaining = Math.max(0, PACE_LIMIT_SEC - elapsedSec);
    var pct = Math.max(0, Math.min(100, (remaining / PACE_LIMIT_SEC) * 100));
    var fill = $('diag-pace-fill');
    var timerText = $('diag-pace-timer');
    var flag = $('diag-pace-flag');

    fill.style.width = pct.toFixed(1) + '%';

    if (elapsedSec >= PACE_LIMIT_SEC) {
      fill.className = 'diag-pace-fill is-drift';
      timerText.className = 'diag-pace-timer is-drift';
      timerText.textContent = '0.0 с (+' + Math.floor(elapsedSec - PACE_LIMIT_SEC) + ' с)';
      flag.hidden = false;
      if (!state.paceDriftLogged) {
        state.paceDriftLogged = true;
        state.paceDrifts += 1;
        adjustTrust(-2);
      }
    } else if (remaining <= 12) {
      fill.className = 'diag-pace-fill is-warn';
      timerText.className = 'diag-pace-timer is-warn';
      timerText.textContent = remaining.toFixed(1) + ' с';
    } else {
      fill.className = 'diag-pace-fill';
      timerText.className = 'diag-pace-timer';
      timerText.textContent = remaining.toFixed(1) + ' с';
    }
  }

  function submitAnswer(optionIdx) {
    if (state.stage !== 'run' || state.lockedAnswer || !state.currentQuestion) return;
    state.lockedAnswer = true;
    stopQuestionTimer();

    var elapsedMs = Math.max(100, Math.round(performance.now() - state.questionStartedAt));
    var q = state.currentQuestion;
    var isCorrect = optionIdx === q.correctIndex;

    if (elapsedMs < 900) {
      state.fastGuesses += 1;
      adjustTrust(-7);
    } else if (state.pointerMoves === 0 && state.currentIndex >= 1) {
      adjustTrust(-2);
    }

    var btns = $('diag-options').querySelectorAll('.diag-option-btn');
    for (var i = 0; i < btns.length; i++) {
      btns[i].disabled = true;
      if (i === optionIdx) {
        btns[i].classList.add('is-picked');
        btns[i].classList.add(isCorrect ? 'is-correct-flash' : 'is-wrong-flash');
      }
    }

    state.answers.push({
      questionId: q.id,
      level: q.level,
      format: q.format,
      topic: q.topic,
      selectedIndex: optionIdx,
      correctIndex: q.correctIndex,
      isCorrect: isCorrect,
      elapsedMs: elapsedMs,
      paceDrift: elapsedMs > PACE_LIMIT_SEC * 1000
    });

    state.currentLevel = isCorrect
      ? Math.min(5, state.currentLevel + 1)
      : Math.max(1, state.currentLevel - 1);
    state.currentIndex += 1;

    window.setTimeout(function () {
      if (state.stage === 'run') {
        loadQuestionAtStep();
      }
    }, 360);
  }

