  function wrapLines(ctx, text, maxWidth) {
    var words = String(text || '').split(/\s+/);
    var lines = [];
    var line = '';
    for (var i = 0; i < words.length; i++) {
      var word = words[i];
      var test = line ? line + ' ' + word : word;
      if (ctx.measureText(test).width > maxWidth && line) {
        lines.push(line);
        line = word;
      } else {
        line = test;
      }
    }
    if (line) lines.push(line);
    return lines;
  }

  function drawRoundedRect(ctx, x, y, w, h, r) {
    var rad = Math.min(r, w / 2, h / 2);
    ctx.beginPath();
    ctx.moveTo(x + rad, y);
    ctx.lineTo(x + w - rad, y);
    ctx.quadraticCurveTo(x + w, y, x + w, y + rad);
    ctx.lineTo(x + w, y + h - rad);
    ctx.quadraticCurveTo(x + w, y + h, x + w - rad, y + h);
    ctx.lineTo(x + rad, y + h);
    ctx.quadraticCurveTo(x, y + h, x, y + h - rad);
    ctx.lineTo(x, y + rad);
    ctx.quadraticCurveTo(x, y, x + rad, y);
    ctx.closePath();
  }

  function seededRand(seedStr) {
    var h = 2166136261;
    for (var i = 0; i < seedStr.length; i++) {
      h ^= seedStr.charCodeAt(i);
      h = Math.imul(h, 16777619);
    }
    return function () {
      h += 0x6D2B79F5;
      var t = Math.imul(h ^ (h >>> 15), 1 | h);
      t ^= t + Math.imul(t ^ (t >>> 7), 61 | t);
      return ((t ^ (t >>> 14)) >>> 0) / 4294967296;
    };
  }

  function drawAntiOcrOverlay(ctx, w, h, pal, seedStr) {
    var rand = seededRand(seedStr);

    // Subtle hairline architectural grid
    ctx.save();
    ctx.strokeStyle = pal.watermark;
    ctx.lineWidth = 1;
    for (var gx = 28; gx < w; gx += 44) {
      ctx.beginPath();
      ctx.moveTo(gx, 0);
      ctx.lineTo(gx, h);
      ctx.stroke();
    }

    // Diagonal anti-OCR watermark text
    ctx.fillStyle = pal.watermark;
    ctx.font = '600 11px "JetBrains Mono", monospace';
    ctx.translate(w / 2, h / 2);
    ctx.rotate(-0.22);
    for (var wy = -h; wy <= h; wy += 88) {
      for (var wx = -w; wx <= w; wx += 290) {
        ctx.fillText('STRICTAI ANTI-OCR  //  VERIFIED CAT', wx, wy);
      }
    }
    ctx.restore();

    // Deterministic anti-OCR micro-noise specks
    ctx.save();
    var count = Math.min(260, Math.floor((w * h) / 1400));
    for (var i = 0; i < count; i++) {
      var nx = rand() * w;
      var ny = rand() * h;
      ctx.fillStyle = i % 2 === 0 ? pal.noiseLight : pal.noiseDark;
      ctx.fillRect(nx, ny, 1.4, 1.4);
    }
    ctx.restore();
  }

  function measureVisualHeight(ctx, visual, innerW) {
    if (!visual) return 0;
    if (visual.type === 'table') {
      return 38 + visual.rows.length * 36 + 12;
    }
    if (visual.type === 'steps') {
      ctx.font = '400 13.5px Inter, sans-serif';
      var total = 40;
      for (var i = 0; i < visual.items.length; i++) {
        var lines = wrapLines(ctx, visual.items[i], innerW - 44);
        total += Math.max(30, lines.length * 19 + 14);
      }
      return total + 8;
    }
    if (visual.type === 'trap') {
      ctx.font = '400 13px Inter, sans-serif';
      var noteLines = wrapLines(ctx, visual.note, innerW - 32);
      return 86 + noteLines.length * 18;
    }
    if (visual.type === 'diagram') {
      if (visual.kind === 'preposition_flow' || visual.kind === 'verb_aspect') {
        return 146;
      }
      if (visual.kind === 'syntax_tree' || visual.kind === 'timeline') {
        return 142;
      }
      return 184;
    }
    return 120;
  }

