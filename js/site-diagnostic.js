  function mapScoreToCefr(score) {
    if (score >= 195) return 'C2';
    if (score >= 184) return 'C1';
    if (score >= 167) return 'B2';
    if (score >= 145) return 'B1';
    if (score >= 125) return 'A2';
    return 'A1';
  }

  function computeDiagnosticResult() {
    var disc = getDisciplineMeta(state.selectedSubject);
    var uni = getUniMeta(state.selectedUniId);
    var pool = QUESTION_BANK[state.selectedSubject] || QUESTION_BANK['Математика'];

    var rawScore = 136;
    var maxLevelReached = 3;
    var correctCount = 0;

    for (var i = 0; i < state.answers.length; i++) {
      var ans = state.answers[i];
      if (ans.level > maxLevelReached) maxLevelReached = ans.level;
      if (ans.isCorrect) {
        correctCount += 1;
        rawScore += 6 + ans.level * 1.4;
      } else {
        rawScore -= (6 - ans.level) * 1.6;
      }
    }

    if (correctCount === TOTAL_QUESTIONS && state.paceDrifts === 0) {
      rawScore += 4;
    }

    var predictedScore = Math.max(106, Math.min(198, Math.round(rawScore)));
    var cefrLevel = disc.category === 'lang' ? mapScoreToCefr(predictedScore) : 'B2';
    var trustScore = Math.max(40, Math.min(100, Math.round(state.trustScore)));

    // Rank weak topics: incorrect answers first (highest impact), then slowest/hardest
    var wrongCandidates = [];
    var otherCandidates = [];
    var seenTopics = {};

    for (var j = 0; j < state.answers.length; j++) {
      var a = state.answers[j];
      var qObj = null;
      for (var k = 0; k < pool.length; k++) {
        if (pool[k].id === a.questionId) {
          qObj = pool[k];
          break;
        }
      }
      if (!qObj) continue;
      if (!a.isCorrect) {
        wrongCandidates.push({ q: qObj, answer: a, impact: 11 - a.level });
        seenTopics[qObj.topic] = true;
      } else {
        otherCandidates.push({ q: qObj, answer: a, impact: Math.max(4, 9 - a.level) });
      }
    }

    wrongCandidates.sort(function (x, y) { return y.impact - x.impact; });
    otherCandidates.sort(function (x, y) { return y.answer.elapsedMs - x.answer.elapsedMs; });

    var prioritized = wrongCandidates.slice();
    for (var m = 0; m < otherCandidates.length && prioritized.length < 3; m++) {
      if (!seenTopics[otherCandidates[m].q.topic]) {
        prioritized.push(otherCandidates[m]);
        seenTopics[otherCandidates[m].q.topic] = true;
      }
    }
    for (var p = 0; p < pool.length && prioritized.length < 3; p++) {
      if (!seenTopics[pool[p].topic]) {
        prioritized.push({ q: pool[p], answer: null, impact: 6 });
        seenTopics[pool[p].topic] = true;
      }
    }

    var topic1 = prioritized[0];
    var topic2 = prioritized[1];
    var topic3 = prioritized[2];

    var weakTopicStrings = [
      topic1.q.topic,
      topic2.q.topic,
      topic3.q.topic
    ];

    return {
      discipline: disc,
      university: uni,
      predictedScore: predictedScore,
      cefrLevel: cefrLevel,
      correctCount: correctCount,
      maxLevelReached: maxLevelReached,
      trustScore: trustScore,
      weakTopics: weakTopicStrings,
      detailedTopics: [
        {
          topic: topic1.q.topic,
          impact: Math.max(7, Math.min(12, Math.round(topic1.impact))),
          socratic: topic1.q.socratic,
          wasWrong: Boolean(topic1.answer && !topic1.answer.isCorrect)
        },
        {
          topic: topic2.q.topic,
          impact: Math.max(5, Math.min(9, Math.round(topic2.impact))),
          hintPreview: topic2.q.socratic.pattern
        },
        {
          topic: topic3.q.topic,
          impact: Math.max(4, Math.min(8, Math.round(topic3.impact))),
          hintPreview: topic3.q.socratic.pattern
        }
      ]
    };
  }

  async function finishDiagnosticSession() {
    stopQuestionTimer();
    var res = computeDiagnosticResult();
    state.resultPayload = res;

    var draftPayload = {
      predictedScore: res.predictedScore,
      cefrLevel: res.cefrLevel,
      subject: res.discipline.id,
      targetUni: res.university.id === 'none' ? '' : res.university.label,
      weakTopics: res.weakTopics,
      trustScore: res.trustScore,
      unwrappedError: {
        topic: res.detailedTopics[0].topic,
        pattern: res.detailedTopics[0].socratic.pattern,
        trap: res.detailedTopics[0].socratic.trap,
        steps: res.detailedTopics[0].socratic.steps
      },
      answers: state.answers,
      recommendedTier: 'StrictPass Pro'
    };

    var saved = null;
    if (window.StrictAuth && typeof window.StrictAuth.saveDiagnosticDraft === 'function') {
      try {
        saved = await window.StrictAuth.saveDiagnosticDraft(draftPayload);
      } catch (_err) {
        saved = null;
      }
    }
    if (!saved) {
      saved = Object.assign({ sid: 'diag_' + Date.now().toString(36) }, draftPayload);
    }

    state.savedRecord = saved;
    switchStage('result');
    renderResultStage();
  }

